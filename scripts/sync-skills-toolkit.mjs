/** Refresh vendored skill data without executing any upstream skill or script. */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/sync-skills-toolkit.mjs /path/to/skills-checkout");
const config = JSON.parse(await readFile(resolve(root, "data/skills-toolkit/sources.json"), "utf8"));
const git = (...args) => execFileSync("git", ["-C", resolve(source), ...args], { maxBuffer: 10 * 1024 * 1024 });
const head = git("rev-parse", "HEAD").toString().trim();
if (head !== config.commit) throw new Error(`Expected pinned source commit ${config.commit}; found ${head}.`);
const readSource = (path) => git("show", `${config.commit}:${path}`);
const license = readSource("LICENSE").toString("utf8");
const metadata = [];
const manifest = {};
const checksums = {};
await mkdir(resolve(root, "public/skills-toolkit"), { recursive: true });

for (const selected of config.skills) {
	const sourcePaths = git("ls-tree", "-r", "--name-only", config.commit, "--", selected.slug).toString().trim().split("\n").filter(Boolean).sort();
	const sourceFiles = sourcePaths.map((path) => {
		const bytes = readSource(path);
		const relative = path.slice(selected.slug.length + 1);
		let content;
		let encoding = "utf8";
		try {
			content = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
			if (content.includes("\0")) throw new Error("Binary file");
		} catch { content = bytes.toString("base64"); encoding = "base64"; }
		checksums[`${selected.slug}/${relative}`] = { bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") };
		return { path: relative, content, encoding };
	});
	const entry = sourceFiles.find((file) => file.path === "SKILL.md");
	if (!entry) throw new Error(`${selected.slug} has no root SKILL.md`);
	const frontmatter = /^(?:\uFEFF)?---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(entry.content);
	if (!frontmatter) throw new Error(`${selected.slug} has no YAML frontmatter`);
	const fields = parse(frontmatter[1]);
	if (fields.name !== selected.slug) throw new Error(`Original name differs for ${selected.slug}`);
	if (typeof fields.description !== "string" || fields.description.length > 1024) throw new Error(`Invalid description for ${selected.slug}`);
	const url = `${config.repository}/tree/${config.commit}/${selected.slug}`;
	const attribution = `# Source attribution\n\nDisplay name: ${selected.name}\nOriginal skill name: ${selected.slug}\n\nSource: ${url}\nRepository: ${config.repository}\nPinned commit: ${config.commit}\n\nAll files from the original skill directory are preserved byte for byte, including scripts, references, assets, and any other supporting directories. This file and SOURCE-LICENSE-APACHE-2.0.txt were added by the toolkit; original skill content has not been modified.\n\nThe source repository distributes an Apache License 2.0, reproduced in SOURCE-LICENSE-APACHE-2.0.txt. Original copyright and attribution notices remain in the source files.${fields.license ? ` The original SKILL.md additionally declares license: ${fields.license}. No separate license text for that declaration was provided in the source skill directory; the original declaration is retained.` : ""}\n\nDisplay labels and categories are toolkit metadata; the original frontmatter name, content, and relative paths are unchanged. References to sibling skills or tools outside this package remain upstream references; those other skills are not included unless separately selected. Supporting scripts are distributed as data and are never run by the toolkit.\n`;
	const files = [...sourceFiles,
		{ path: "SOURCE-LICENSE-APACHE-2.0.txt", content: license, encoding: "utf8" },
		{ path: "SOURCE-ATTRIBUTION.md", content: attribution, encoding: "utf8" },
	];
	const skill = { id: `builtin:${selected.slug}`, slug: selected.slug, name: selected.name, description: fields.description, category: selected.category, source: { kind: "builtin", label: "darkweb19/skills", url }, files };
	await writeFile(resolve(root, `public/skills-toolkit/${selected.slug}.json`), JSON.stringify(skill) + "\n");
	metadata.push({ ...skill, files: [] });
	manifest[selected.slug] = { fileCount: files.length, byteSize: files.reduce((total, file) => total + Buffer.byteLength(file.content, file.encoding === "base64" ? "base64" : "utf8"), 0), paths: files.map((file) => file.path) };
}

const generated = `// Generated by scripts/sync-skills-toolkit.mjs. Source: ${config.repository}/tree/${config.commit}\n// Original skill/license bytes live in public/skills-toolkit/*.json; do not edit generated data.\nimport type { SkillPackage } from "./types";\n\n/** Lightweight metadata only: loadBuiltinSkill must hydrate files before validation/export. */\nexport const BUILTIN_SKILLS: SkillPackage[] = ${JSON.stringify(metadata, null, "\t")};\n\nexport interface BuiltinSkillManifest { fileCount: number; byteSize: number; paths: string[]; }\nexport const BUILTIN_SKILL_MANIFEST: Record<string, BuiltinSkillManifest> = ${JSON.stringify(manifest, null, "\t")};\n`;
await writeFile(resolve(root, "lib/skills-toolkit/catalog-data.ts"), generated);
await writeFile(resolve(root, "data/skills-toolkit/source-checksums.json"), JSON.stringify({ repository: config.repository, commit: config.commit, files: checksums }, null, 2) + "\n");
console.log(`Synced ${metadata.length} pinned skills, ${Object.keys(checksums).length} original files, ${Object.values(manifest).reduce((total, item) => total + item.byteSize, 0)} bytes including attribution/licenses.`);
